/** The mark carried by every image of simulated data. */
export const SIMULATED_MARK = 'SIMULATED DATA';

/** Pixel mask of `text` (upper case, digits and a few signs) with a margin, at an integer scale. */
export function textMask(text: string, scale: number): { width: number; height: number; mask: Uint8Array } {
  const pad = 2 * scale;
  const width = text.length * 6 * scale - scale + 2 * pad;
  const height = 7 * scale + 2 * pad;
  const mask = new Uint8Array(width * height);
  [...text.toUpperCase()].forEach((ch, c) => {
    const g = GLYPHS[ch] ?? GLYPHS[' ']!;
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (g[gy]![gx] !== '#') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) mask[(pad + gy * scale + sy) * width + pad + (c * 6 + gx) * scale + sx] = 1;
        }
      }
    }
  });
  return { width, height, mask };
}
