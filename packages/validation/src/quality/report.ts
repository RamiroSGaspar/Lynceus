/**
 * The technical report of the synthetic validation, `out/quality-validation.md`.
 * Everything in it comes from `analyzeValidation`; it has no dates or timings, so the
 * same rows give the same bytes. Simulated data.
 */
import { ERROR_FEATURES } from '@app/core/rules/simulatedErrorModel';
import type { MeasureResult, ValidationMeasure, ValidationPartition } from '@app/core/dataset/validationSummary';
import { TOLERANCES, type BreakdownRow, type ErrorStats, type ValidationResult } from './analysis';

const PARTITION_NAMES: Record<ValidationPartition, string> = {
  development: 'Development (A, B, D; development families)',
  'test-anatomy': 'Test P1, new anatomy (C, every family)',
  'test-family': 'Test P2, new failure (A, B, D; edge fade and new combinations)',
};
const MEASURE_NAMES: Record<ValidationMeasure, string> = { trt: 'Change of the 0–250 µm ring (TRT)', roughness: 'Change of Bruch’s membrane roughness' };

const f = (v: number, d = 2) => (Number.isFinite(v) ? v.toFixed(d) : '—');
const s = (v: number, d = 2) => (Number.isFinite(v) ? `${v >= 0 ? '+' : ''}${v.toFixed(d)}` : '—');
const pct = (v: number, d = 1) => (Number.isFinite(v) ? `${(100 * v).toFixed(d)} %` : '—');

function statsCells(e: ErrorStats): string {
  return `${e.n} | ${e.eyes} | ${s(e.bias)} | ${f(e.sd)} | ${f(e.rmse)} | ${f(e.mae)} | ${f(e.maxAbs)}`;
}

function breakdownTable(title: string, rows: readonly BreakdownRow[]): string[] {
  return [
    `| ${title} | TRT pairs | eyes | bias | SD | RMSE | MAE | max | roughness pairs | eyes | bias | SD | RMSE | MAE | max |`,
    '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.key} | ${statsCells(r.trt)} | ${statsCells(r.roughness)} |`),
  ];
}

function resultLine(name: string, r: MeasureResult): string {
  return `| ${name} | ${r.pairs} | ${r.eyes} | ${s(r.biasUm)} | ${f(r.rmseUm)} | ${f(r.maeUm)} | ${f(r.maxAbsUm)} | ${f(r.medianSeUm)} | ${pct(r.coverage)} (${pct(r.coverageLow)}–${pct(r.coverageHigh)}) | ${pct(r.beyond3Se)} |`;
}

export function renderReport(result: ValidationResult): string {
  const { summary, spec, fits } = result;
  const formula = (measure: ValidationMeasure) => {
    const term = spec[measure];
    const parts = [term.intercept.toFixed(4), ...term.terms.map((t) => `${t.beta.toFixed(4)} · z_${t.feature}`)];
    return `s(x) = exp(${parts.join(' + ')}) µm, σ = ${spec.calibration[measure].toFixed(4)} · √(s(today)² + s(reference)²)`;
  };
  const lines: string[] = [
    '# Synthetic validation of the engine’s error',
    '',
    `> ${summary.notice} Every exam in this report is fictional: the virtual instrument drew it on one of`,
    '> eight virtual eyes of four invented crew members, with the same layer model the engine expects.',
    '> The errors below are the engine against the known truth of those virtual eyes. They are not a',
    '> validation on people, not the performance of the real tomograph, and not a diagnosis. The error on',
    '> real exams is larger and unknown. Probabilities refer to the simulator’s measurement, not to SANS.',
    '',
    `Protocol \`${summary.protocol}\` (\`packages/validation/protocol.md\`), engine ${summary.versions.engine}, ${summary.versions.instrument}`,
    `(exam format ${summary.versions.examFormat}, scan format ${summary.versions.scanFormat}), model \`${summary.versions.model}\`.`,
    'Generated by `pnpm --filter @app/validation quality:fit` from `out/quality-rows.json` (written by `quality:run`;',
    'timing in `out/quality-run.md`).',
    '',
    '## Decision',
    '',
    summary.decision.activate
      ? '**Every criterion fixed before the final test passed: the model can replace the provisional one.**'
      : '**At least one criterion fixed before the final test failed: the provisional model stays the default.**',
    '',
    '| Criterion | Partition | Measure | Value | Limit | Passed |',
    '|---|---|---|---|---|---|',
    ...summary.decision.criteria.map((c) => `| ${c.id} | ${c.partition} | ${c.measure} | ${Number.isInteger(c.value) ? c.value : f(c.value, 4)} | ${c.comparison} ${c.limit} | ${c.passed ? 'yes' : '**no**'} |`),
    '',
    'Tolerances are this project’s engineering choices (protocol, section 6); NASA’s thresholds of 19.4 µm,',
    '55 µm and 2.8 µm describe the eye, not the engine.',
    '',
    '## Sample',
    '',
    `${summary.sample.captures} captures: ${summary.sample.references} pre-flight references and ${summary.sample.captures - summary.sample.references} follow-ups, of`,
    `${summary.sample.eyes} eyes of ${summary.sample.crewMembers} fictional crew members. Many captures of one eye are not many eyes: the`,
    'columns "eyes" say how many independent anatomies stand behind each number. The frequency of each failure',
    'is a choice of the experiment, not the frequency of failures in astronauts.',
    '',
    '| Partition | Crew | Eyes | Captures | Refused by the engine | Accepted but outside the model | Pairs used |',
    '|---|---|---|---|---|---|---|',
    ...(Object.keys(summary.partitions) as ValidationPartition[]).map((p) => {
      const x = summary.partitions[p];
      return `| ${PARTITION_NAMES[p]} | ${x.crew.join(', ')} | ${x.eyes} | ${x.captures} | ${x.engineRefused} | ${x.modelRefused} | ${x.pairs} |`;
    }),
    '',
    'P2 shares eyes and references with development: it tests unseen failures, not unseen anatomy.',
    '',
    '## Model',
    '',
    'Fixed family (protocol, section 4): normal error of zero mean, no bias correction. Variables, all computed by',
    'the engine from the image and oriented so that more is a worse capture:',
    '',
    '| Variable | Transformation | Development range (min – max) |',
    '|---|---|---|',
    ...(Object.keys(ERROR_FEATURES) as (keyof typeof ERROR_FEATURES)[]).map((id) => `| z_${id} | ${ERROR_FEATURES[id].transform} | ${f(spec.domain[id].min, 4)} – ${f(spec.domain[id].max, 4)} |`),
    '',
    'An exam with a variable that is not a number, or above the development maximum, is not supported: the',
    'application says it cannot measure. Below the minimum the variable is clipped, so the error is never',
    'extrapolated below what was measured.',
    '',
  ];
  for (const measure of ['trt', 'roughness'] as const) {
    const fit = fits[measure];
    lines.push(
      `### ${MEASURE_NAMES[measure]}`,
      '',
      `\`${formula(measure)}\``,
      '',
      `Calibration: out-of-fold |z| at the 95th percentile ${f(fit.q95AbsZ, 3)}, so k = max(1, ${f(fit.q95AbsZ, 3)} / 1.96) = ${f(fit.k, 4)}.`,
      '',
      '| Step | Variables | Out-of-sample −log L | Coefficients | Outcome |',
      '|---|---|---|---|---|',
      ...fit.steps.map((st, i) => `| ${i} | ${st.features.join(', ') || '(constant)'} | ${f(st.cvNll, 2)} | ${st.betas.map((b) => f(b, 4)).join(', ') || '—'} | ${st.accepted ? 'chosen' : st.note} |`),
      '',
    );
  }
  lines.push('## Error of the changes, pairs the engine and the model accepted', '', 'µm. Coverage: fraction of pairs whose true change is inside ±1.96 σ, with its Wilson 95 % interval.', '');
  lines.push('| Partition / measure | Pairs | Eyes | Bias | RMSE | MAE | Max | Median σ | Coverage of ±1.96 σ | > 3 σ |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const p of Object.keys(summary.partitions) as ValidationPartition[]) {
    for (const m of ['trt', 'roughness'] as const) lines.push(resultLine(`${PARTITION_NAMES[p]} · ${m}`, summary.partitions[p].results[m]));
  }
  lines.push('', 'RMSE is not used as a standard deviation and 1.96 × RMSE is not taken as coverage: σ comes from the model and coverage is counted.', '');
  lines.push('### Tails of z = error / σ against a normal', '', '| Partition / measure | |z| > 1 | > 1.96 | > 2.58 | > 3 |', '|---|---|---|---|---|');
  for (const p of Object.keys(summary.partitions) as ValidationPartition[]) {
    for (const m of ['trt', 'roughness'] as const) {
      const t = result.tails[p][m];
      lines.push(`| ${p} · ${m} | ${t.map((x) => `${pct(x.observed)} (normal ${pct(x.expected)})`).join(' | ')} |`);
    }
  }
  lines.push('', 'This checks the normal approximation behind `probabilityBeyond` on these simulated errors only.', '');
  lines.push('### Thresholds', '', 'Decision on the measured value against the decision on the true value; Brier score of the probability the rules give.', '');
  lines.push('| Partition | Threshold | Pairs | Decided differently | Brier | Pairs with probability 10–90 % | of which truly beyond | their mean probability |', '|---|---|---|---|---|---|---|---|');
  for (const p of Object.keys(summary.partitions) as ValidationPartition[]) {
    for (const t of result.thresholds[p]) lines.push(`| ${p} | ${t.id} (${t.comparison} ${t.thresholdUm} µm) | ${t.pairs} | ${t.misclassified} | ${f(t.brier, 5)} | ${t.uncertain} | ${t.uncertainExceeded} | ${pct(t.uncertainMeanProbability)} |`);
  }
  lines.push('');
  for (const p of Object.keys(summary.partitions) as ValidationPartition[]) {
    lines.push(`### ${PARTITION_NAMES[p]}: by quality of today’s exam`, '', ...breakdownTable('Quality', result.byQuality[p]), '');
    lines.push(`### ${PARTITION_NAMES[p]}: by family`, '', ...breakdownTable('Family', result.byFamily[p]), '');
    lines.push(`### ${PARTITION_NAMES[p]}: by eye`, '', ...breakdownTable('Eye', result.byEye[p]), '');
  }
  lines.push(
    '## Error of each exam and independence',
    '',
    '| Measure | Exams | Eyes | Bias | SD | RMSE | MAE | Max | SD of the per-eye mean |',
    '|---|---|---|---|---|---|---|---|---|',
    ...result.examErrors.map((e) => `| ${e.measure} | ${statsCells(e.stats)} | ${f(e.perEyeMeanSd)} |`),
    '',
    `Correlation between the error of today’s exam and that of its reference, over ${summary.examErrorCorrelation.pairs} accepted pairs`,
    `(${summary.examErrorCorrelation.references} distinct references, so the pairs are not independent): TRT ${f(summary.examErrorCorrelation.trt, 3)},`,
    `roughness ${f(summary.examErrorCorrelation.roughness, 3)}. The model is fitted on the errors of the changes themselves; its two terms`,
    'are a parametrisation, not an assumption that both errors are independent.',
    '',
    '## Change since the previous control (secondary)',
    '',
    'Two clean follow-ups of the same eye against the same reference, consecutive sampled days; σ from the same model.',
    '',
    '| Partition | Pairs | Eyes | Bias | RMSE | Max | Coverage of ±1.96 σ |',
    '|---|---|---|---|---|---|---|',
    ...result.sincePrevious.map((x) => `| ${x.partition} | ${x.pairs} | ${x.eyes} | ${s(x.stats.bias)} | ${f(x.stats.rmse)} | ${f(x.stats.maxAbs)} | ${pct(x.coverage)} (${pct(x.coverageLow)}–${pct(x.coverageHigh)}) |`),
    '',
    '## Refusals',
    '',
    `Accepted pairs with an error beyond the engineering tolerance (TRT > ${TOLERANCES.trtChangeUm} µm: ${summary.grossErrors.trt}; roughness > ${TOLERANCES.roughnessChangeUm} µm: ${summary.grossErrors.roughness}).`,
    summary.grossErrors.trt + summary.grossErrors.roughness === 0
      ? 'There is no positive class among accepted captures, so no quality classifier was trained and no AUC is given; the acceptance rule is the engine’s refusals plus the model’s domain.'
      : 'These are the only examples of a bad accepted capture; they are listed so the acceptance rule can be judged, not to train a classifier on.',
    '',
    '| Partition | Family | Level | Planned | Refused by the engine | Outside the model | Reasons |',
    '|---|---|---|---|---|---|---|',
    ...result.rejections.map((r) => `| ${r.partition} | ${r.family} | ${r.level} | ${r.planned} | ${r.engineRefused} | ${r.modelRefused} | ${r.reasons.join('; ') || '—'} |`),
    '',
    '## Limits',
    '',
    '- Four fictional people and eight eyes; P1 is two eyes of one person. Coverage intervals count pairs, which',
    '  are not independent within an eye.',
    '- The instrument and the engine share the layer model: real anatomy, opacities, vessels in the cup and',
    '  tracking artefacts are missing, so these errors are a lower bound for real exams.',
    '- The quality index (~25 dB for a clean capture) is this simulator’s implementation of the definition in',
    '  specification 01, 5.4, not a validated calibration of the real instrument’s index.',
    '- Captures with explicit failure conditions aim at 30 dB without scan-to-scan variation, as the instrument',
    '  is written. The mix of failures is the experiment’s choice.',
    '',
  );
  return lines.join('\n');
}
